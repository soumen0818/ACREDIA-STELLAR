-- =====================================================================
-- ACREDIA-STELLAR — PRIVATE CREDENTIAL DOCUMENTS, SHARE LINKS, EXPIRY (IDEMPOTENT)
-- Codebase review 2026-10-30, §3.11 (docs/reviews/2026-10-29-codebase-review.md)
-- =====================================================================
-- The problem:
--   Credential documents (diploma scans) and credential JSON (name, degree,
--   GPA, marks, wallet) were pinned to public IPFS unencrypted, and each
--   credential's IPFS address was stored on-chain. Anyone could enumerate
--   the contract and read every student's documents and grades.
--
-- Decision (storage model B): the chain stores only the credential hash.
-- The credential JSON stays in credentials.metadata (as before); the
-- document goes to a private Storage bucket, and the JSON records the
-- document's SHA-256 digest, so the on-chain hash still covers it. Details
-- are shown only through the student's unguessable share link; a bare
-- token id shows status only.
--
-- What this file does:
--   1. Adds to public.credentials:
--        document_path   — object path in the private bucket (nullable:
--                          CSV-issued credentials have no uploaded file)
--        document_sha256 — hex SHA-256 of that document
--        expires_at      — copy of the on-chain expiry for display; the
--                          contract stays authoritative
--        share_token     — random UUID for /credentials/<share_token>,
--                          generated by the database for every row
--   2. Makes ipfs_hash nullable: new credentials have no IPFS content.
--   3. Drops the trigger that registered every new credential's ipfs_hash
--      for pinning. With ipfs_hash NULL it would fail every insert. The
--      credential_pins table itself is kept (a later cleanup drops it).
--   4. Creates the private bucket `credential-documents`. It is not public
--      and has no policies on storage.objects, so anon and authenticated
--      users can neither read nor write it; only server routes using the
--      service role can, and they hand out short-lived signed URLs.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. New columns
-- ---------------------------------------------------------------------
ALTER TABLE public.credentials
    ADD COLUMN IF NOT EXISTS document_path   TEXT,
    ADD COLUMN IF NOT EXISTS document_sha256 TEXT,
    ADD COLUMN IF NOT EXISTS expires_at      TIMESTAMP WITH TIME ZONE,
    ADD COLUMN IF NOT EXISTS share_token     UUID NOT NULL DEFAULT gen_random_uuid();

CREATE UNIQUE INDEX IF NOT EXISTS idx_credentials_share_token
    ON public.credentials (share_token);

ALTER TABLE public.credentials DROP CONSTRAINT IF EXISTS credentials_document_sha256_format;
ALTER TABLE public.credentials
    ADD CONSTRAINT credentials_document_sha256_format
    CHECK (document_sha256 IS NULL OR document_sha256 ~ '^[0-9a-f]{64}$');

COMMENT ON COLUMN public.credentials.document_path IS
    'Object path of the credential document in the private credential-documents bucket.';
COMMENT ON COLUMN public.credentials.document_sha256 IS
    'Hex SHA-256 of the document; also recorded in the credential JSON (evidence id urn:sha256:...), so the on-chain hash covers it.';
COMMENT ON COLUMN public.credentials.expires_at IS
    'Copy of the on-chain expires_at for display and filtering. The contract is authoritative.';
COMMENT ON COLUMN public.credentials.share_token IS
    'Unguessable token for the student''s share link (/credentials/<share_token>). A bare token id shows status only.';

-- ---------------------------------------------------------------------
-- 2. No IPFS content for new credentials
-- ---------------------------------------------------------------------
ALTER TABLE public.credentials ALTER COLUMN ipfs_hash DROP NOT NULL;

-- ---------------------------------------------------------------------
-- 3. Stop registering pins (table kept for a later cleanup)
-- ---------------------------------------------------------------------
DROP TRIGGER IF EXISTS trg_register_credential_pins ON public.credentials;
DROP FUNCTION IF EXISTS public.register_credential_pins();

-- ---------------------------------------------------------------------
-- 4. Private document bucket
-- ---------------------------------------------------------------------
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
    'credential-documents',
    'credential-documents',
    false,
    10485760,
    ARRAY['application/pdf', 'image/jpeg', 'image/png']
)
ON CONFLICT (id) DO UPDATE
SET public             = false,
    file_size_limit    = EXCLUDED.file_size_limit,
    allowed_mime_types = EXCLUDED.allowed_mime_types;

COMMIT;
